#!/usr/bin/env python3
"""Writes src/widths.zig from the Unicode EastAsianWidth.txt.

    scripts/gen-widths.py EastAsianWidth.txt > src/widths.zig

Source: https://www.unicode.org/Public/UCD/latest/ucd/EastAsianWidth.txt
(Unicode Standard Annex #11). Takes the code points with width W (wide) or F
(fullwidth), including the unassigned ones the file gives a width to.
"""
import re
import sys

ranges, version = [], "?"
for line in open(sys.argv[1], encoding="utf-8"):
    m = re.match(r"# EastAsianWidth-([\d.]+)\.txt", line)
    if m:
        version = m.group(1)
    m = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z]+)", line)
    if m and m.group(3) in ("W", "F"):
        lo = int(m.group(1), 16)
        ranges.append((lo, int(m.group(2) or m.group(1), 16)))

merged = []
for lo, hi in sorted(ranges):
    if merged and lo <= merged[-1][1] + 1:
        merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
    else:
        merged.append((lo, hi))

print("//! Generated by scripts/gen-widths.py from EastAsianWidth.txt %s; do not edit." % version)
print()
print("/// The first and last code point of each run of wide and fullwidth characters,")
print("/// in order.")
print("pub const wide = [_][2]u21{")
for lo, hi in merged:
    print("    .{ 0x%x, 0x%x }," % (lo, hi))
print("};")
