#!/usr/bin/env python3
"""Writes src/unicode_tables.zig from the Unicode Character Database.

    scripts/gen-unicode.py UnicodeData.txt CaseFolding.txt > src/unicode_tables.zig

Source: https://www.unicode.org/Public/UCD/latest/ucd/. CommonMark 0.31.2
defines "Unicode punctuation" as general categories P and S, "Unicode
whitespace" as category Zs and four ASCII characters, and matches link labels
with the Unicode case fold (full folding: statuses C and F).
"""
import re
import sys


def categories(path):
    """Yields (first, last, general category)."""
    first = None
    for line in open(path, encoding="utf-8"):
        fields = line.split(";")
        cp, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = cp
            continue
        yield (first if name.endswith(", Last>") else cp), cp, category


def runs(points):
    merged = []
    for lo, hi in sorted(points):
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
        else:
            merged.append((lo, hi))
    return merged


data = list(categories(sys.argv[1]))
punct = runs((lo, hi) for lo, hi, c in data if c[0] in "PS" and hi >= 0x80)
spaces = runs((lo, hi) for lo, hi, c in data if c == "Zs" and hi >= 0x80)

folds, version = [], "?"
for line in open(sys.argv[2], encoding="utf-8"):
    m = re.match(r"# CaseFolding-([\d.]+)\.txt", line)
    if m:
        version = m.group(1)
    m = re.match(r"([0-9A-F]+); ([CF]); ([0-9A-F ]+);", line)
    if m and int(m.group(1), 16) >= 0x80:
        to = "".join("\\u{%x}" % int(x, 16) for x in m.group(3).split())
        folds.append((int(m.group(1), 16), to))

print("//! Generated by scripts/gen-unicode.py from the Unicode Character Database %s;" % version)
print("//! do not edit. ASCII is left out: the code handles it directly.")
for name, doc, table in (
    ("punctuation", "General categories P and S", punct),
    ("space_separators", "General category Zs", spaces),
):
    print()
    print("/// %s: first and last code point of each run, in order." % doc)
    print("pub const %s = [_][2]u21{" % name)
    for lo, hi in table:
        print("    .{ 0x%x, 0x%x }," % (lo, hi))
    print("};")
print()
print("pub const Fold = struct { from: u21, to: []const u8 };")
print()
print("/// Full case folding, in order of `from`.")
print("pub const case_folds = [_]Fold{")
for cp, to in sorted(folds):
    print('    .{ .from = 0x%x, .to = "%s" },' % (cp, to))
print("};")
