#!/usr/bin/env python3
"""Writes src/entities.zig from the WHATWG entities.json.

    scripts/gen-entities.py entities.json > src/entities.zig

Source: https://html.spec.whatwg.org/entities.json (named references that end
in a semicolon; CommonMark only recognises those).
"""
import json, sys

d = json.load(open(sys.argv[1]))
names = sorted(k[1:-1] for k in d if k.endswith(";"))

def lit(s):
    return '"' + "".join("\\u{%x}" % ord(c) for c in s) + '"'

print("//! Generated by scripts/gen-entities.py from the WHATWG entities.json; do not edit.")
print("")
print("const std = @import(\"std\");")
print("")
print("pub const Entry = struct { name: []const u8, value: []const u8 };")
print("")
print("/// Named character references, sorted by name (without `&` and `;`).")
print("pub const table = [_]Entry{")
for n in names:
    print("    .{ .name = \"%s\", .value = %s }," % (n, lit(d["&" + n + ";"]["characters"])))
print("};")
print("")
print("/// The text a named reference stands for, or null.")
print("pub fn lookup(name: []const u8) ?[]const u8 {")
print("    var lo: usize = 0;")
print("    var hi: usize = table.len;")
print("    while (lo < hi) {")
print("        const mid = lo + (hi - lo) / 2;")
print("        switch (std.mem.order(u8, table[mid].name, name)) {")
print("            .eq => return table[mid].value,")
print("            .lt => lo = mid + 1,")
print("            .gt => hi = mid,")
print("        }")
print("    }")
print("    return null;")
print("}")
